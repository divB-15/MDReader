#!/usr/bin/env python3
"""Embed the built single-file frontend into a C++ translation unit."""
import pathlib
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: embed_html.py <index.html> <out.cpp>", file=sys.stderr)
        return 2
    source = pathlib.Path(sys.argv[1])
    target = pathlib.Path(sys.argv[2])
    if not source.exists():
        print(f"missing frontend build: {source}", file=sys.stderr)
        return 1

    html = source.read_text(encoding="utf-8")
    delimiter = "MRHTML"
    while f'){delimiter}"' in html:
        delimiter += "X"

    output = (
        "// Generated by tools/embed_html.py - do not edit.\n"
        "#include <cstddef>\n"
        "#if defined(__GNUC__)\n"
        "#pragma GCC diagnostic ignored \"-Wbidi-chars\"\n"
        "#endif\n\n"
        f'extern const char kEmbeddedHtml[] = R"{delimiter}({html}){delimiter}";\n'
        "extern const size_t kEmbeddedHtmlSize = sizeof(kEmbeddedHtml) - 1;\n"
    )

    if target.exists() and target.read_text(encoding="utf-8") == output:
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(output, encoding="utf-8")
    print(f"embedded {len(html)} bytes of HTML into {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
